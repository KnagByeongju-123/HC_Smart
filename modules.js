/* ===== 무결성 자가점검 — 4개 객체 키 정합 확인 ===== */
function MODULE_CHECK(){
  const keys=Object.keys(MODULE_PRICE);
  const miss={ 세부항목:[], DB:[], 스타터레이아웃:[] };
  keys.forEach(k=>{
    if(!MODULE_SPEC[k]) miss['세부항목'].push(k);
    if(!MODULE_DB[k])   miss['DB'].push(k);
    if(!ST_TPL[k])      miss['스타터레이아웃'].push(k);
  });
  const orphan=[].concat(
    Object.keys(MODULE_SPEC).filter(k=>!(k in MODULE_PRICE)),
    Object.keys(MODULE_DB).filter(k=>!(k in MODULE_PRICE)),
    Object.keys(ST_TPL).filter(k=>!(k in MODULE_PRICE))
  ).filter((v,i,a)=>a.indexOf(v)===i);
  const msg=[];
  Object.keys(miss).forEach(g=>{ if(miss[g].length) msg.push(g+' 누락: '+miss[g].join(', ')); });
  if(orphan.length) msg.push('MODULE_PRICE에 없는 키: '+orphan.join(', '));
  if(msg.length){
    console.warn('[modules.js 점검] '+msg.join(' / '));
    return { ok:false, count:keys.length, msg:msg.join(' / ') };
  }
  return { ok:true, count:keys.length, msg:'' };
}
if(typeof window!=='undefined') window.MODULE_CHECK=MODULE_CHECK;
MODULE_CHECK();
